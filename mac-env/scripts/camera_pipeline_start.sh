#!/usr/bin/env bash
# camera_pipeline_start.sh — open Terminal.app + run the aruco_camera_localizer
# camera+aruco+yoloe pipeline.
#
# Why a Terminal launcher: cv2.imshow on macOS needs a Cocoa session connected
# to WindowServer. A backgrounded process via nohup is detached from that
# session — windows would never open. So we hand the launch off to Terminal.app
# with `open`, which gives the spawned process the right env.
#
# Usage:
#   bash mac-env/scripts/camera_pipeline_start.sh                    # auto-detect via signature
#   bash mac-env/scripts/camera_pipeline_start.sh --camera-id 1      # explicit cv2 idx
#   bash mac-env/scripts/camera_pipeline_start.sh --topic /foo       # custom output topic
#   bash mac-env/scripts/camera_pipeline_start.sh --debug-aruco      # localize_aruco-only (skip yoloe)
#
# Stop:
#   bash mac-env/scripts/camera_pipeline_stop.sh

set -e
SCRIPT_DIR="$(cd "$(dirname "${BASH_SOURCE[0]}")" && pwd)"
# shellcheck source=_lib.sh
. "$SCRIPT_DIR/_lib.sh"

stack_preflight

CAMERA_ID=""
AUTO_DETECT="true"
CAMERA_TOPIC="/camera/image_raw"

while [ $# -gt 0 ]; do
  case "$1" in
    --camera-id)   CAMERA_ID="$2"; AUTO_DETECT="false"; shift 2 ;;
    --camera-id=*) CAMERA_ID="${1#*=}"; AUTO_DETECT="false"; shift ;;
    --topic)       CAMERA_TOPIC="$2"; shift 2 ;;
    --topic=*)     CAMERA_TOPIC="${1#*=}"; shift ;;
    --auto-detect) AUTO_DETECT="true"; shift ;;
    --help|-h)
      sed -n '3,15p' "$0" | sed 's/^# \{0,1\}//'
      exit 0 ;;
    *)
      echo "ERROR: unknown arg '$1'. Use --help." >&2
      exit 1 ;;
  esac
done

LAUNCH_LOG="/tmp/soarm_camera_pipeline.log"
LAUNCH_PIDFILE="/tmp/soarm_camera_pipeline.pid"

# Build the launch command. The dev clone of aruco_camera_localizer holds the
# cached YOLOE / CLIP weight files, so cd there first; ros2 launch inherits
# cwd, and the install dir also has copies (see camera_pipeline_start.sh's
# install step in this commit).
DEV_ARUCO="/Users/aldrininbaraj/Documents/Projects/untitled folder/agents/ros2/repos/aruco_camera_localizer"

# Generate a fresh .command file each invocation so flag changes take effect.
# Lives at /tmp/ — it's a regenerable launcher, not source.
CMD_FILE="/tmp/soarm_camera_pipeline.command"
LAUNCH_ARGS="auto_detect:=$AUTO_DETECT camera_topic:=$CAMERA_TOPIC publish_topic:=$CAMERA_TOPIC"
if [ -n "$CAMERA_ID" ]; then
  LAUNCH_ARGS="$LAUNCH_ARGS camera_id:=$CAMERA_ID"
fi

cat > "$CMD_FILE" <<EOF
#!/bin/bash
# Auto-generated by mac-env/scripts/camera_pipeline_start.sh — do not edit.
# Output is shown in this Terminal AND tee'd to $LAUNCH_LOG so other tools
# (e.g. mac-env diagnostics) can read node startup banners without needing
# to scrape the Terminal window.
cd "$DEV_ARUCO"
/Users/aldrininbaraj/.pixi/bin/pixi run --manifest-path "$MAC_ENV_MANIFEST" bash -c '
  source "$SOARM_WS_SETUP"
  export RMW_IMPLEMENTATION="$RMW_IMPLEMENTATION"
  export CYCLONEDDS_URI="$CYCLONEDDS_URI"
  export KMP_DUPLICATE_LIB_OK="$KMP_DUPLICATE_LIB_OK"
  ros2 launch aruco_camera_localizer camera_pipeline.launch.py $LAUNCH_ARGS
' 2>&1 | tee "$LAUNCH_LOG"
EOF
chmod +x "$CMD_FILE"

# Refuse to start if pipeline is already running.
N_RUNNING=$(pgrep -f "ros2 launch aruco_camera_localizer" | wc -l | tr -d ' ')
if [ "$N_RUNNING" -gt 0 ]; then
  echo "ERROR: camera pipeline already running ($N_RUNNING ros2 launch instance(s))." >&2
  echo "       Stop first: bash $SCRIPT_DIR/camera_pipeline_stop.sh" >&2
  exit 1
fi

echo "== Starting camera pipeline =="
echo "  auto_detect=$AUTO_DETECT  camera_id=${CAMERA_ID:-(unset)}  topic=$CAMERA_TOPIC"
echo "  launcher: $CMD_FILE"
echo ""

open -a Terminal "$CMD_FILE"
echo "  Terminal.app opened. Watch its window for startup logs;"
echo "  cv2 'Merged Detection' window should follow within ~10-15s."
echo ""
echo "Stop:    bash $SCRIPT_DIR/camera_pipeline_stop.sh"
echo ""
echo "If the Terminal window shows 'OpenCV: not authorized to capture video',"
echo "Terminal.app needs Camera permission. Run:"
echo "  bash $SCRIPT_DIR/fix_camera_permissions.sh"
